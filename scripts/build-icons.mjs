/**
 * Builds the icon data the blocks read, from the lucide-static package.
 *
 *   includes/lucide-icons.php     name => inner SVG markup, for render.php
 *                                 (a PHP array, so opcache keeps it in memory)
 *   includes/lucide-tags.json     name => search tags, for the editor's picker
 *   includes/lucide-animated.php  name => animation preset, for the icons
 *                                 Lucide Animated (https://lucide-animated.com)
 *                                 also animates
 *
 * Lucide: https://lucide.dev/icons/ (ISC). Lucide Animated is a set of React
 * components on the motion library, so it is not bundled: only the names of
 * its icons are read (scripts/lucide-animated-names.json), each gets the CSS
 * preset in assets/shared.css closest to its original move, and the editor
 * links to the original at https://lucide-animated.com/icons/<name>.
 *
 * Run: npm run icons (also part of npm run build).
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = resolve( dirname( fileURLToPath( import.meta.url ) ), '..' );
const require = createRequire( import.meta.url );
const nodes = require( 'lucide-static/icon-nodes.json' );
const tags = require( 'lucide-static/tags.json' );
const animated = JSON.parse( readFileSync( resolve( root, 'scripts/lucide-animated-names.json' ), 'utf8' ) ).icons;
const lucideVersion = require( 'lucide-static/package.json' ).version;

const escAttr = ( value ) =>
	String( value ).replace( /&/g, '&amp;' ).replace( /"/g, '&quot;' ).replace( /</g, '&lt;' );

/** One icon's children as SVG markup: Lucide nodes are [tag, attributes]. */
const markup = ( children ) =>
	children
		.map( ( [ tag, attrs ] ) => {
			const list = Object.entries( attrs )
				.filter( ( [ key ] ) => key !== 'key' )
				.map( ( [ key, value ] ) => `${ key }="${ escAttr( value ) }"` )
				.join( ' ' );
			return `<${ tag } ${ list }/>`;
		} )
		.join( '' );

/** The CSS preset closest to how Lucide Animated moves an icon. */
function presetFor( name ) {
	const has = ( ...words ) => words.some( ( w ) => name.includes( w ) );
	if ( has( 'bell', 'alarm', 'vibrate', 'phone-call', 'hand' ) ) return 'wiggle';
	if ( /(^|-)(arrow|chevron|move|corner|redo|undo|forward|reply|send|log-in|log-out)/.test( name ) ) {
		return has( 'up', 'down' ) && ! has( 'left', 'right' ) ? 'nudge-y' : 'nudge-x';
	}
	if ( has( 'settings', 'cog', 'loader', 'refresh', 'rotate', 'fan', 'sun', 'atom', 'orbit', 'loading', 'hourglass', 'timer', 'clock' ) ) {
		return 'spin';
	}
	if ( has( 'heart', 'activity', 'pulse', 'volume', 'audio', 'mic', 'wifi', 'radio', 'signal' ) ) return 'pulse';
	if ( has( 'check', 'chart', 'trending', 'signature', 'pen', 'pencil', 'line', 'route', 'waves', 'spline', 'scribble' ) ) {
		return 'draw';
	}
	if ( has( 'rocket', 'plane', 'cloud', 'ghost', 'balloon', 'feather', 'bird', 'drone' ) ) return 'float';
	if ( has( 'trash', 'delete', 'x', 'ban', 'lock', 'shield-alert', 'triangle-alert', 'circle-alert' ) ) return 'shake';
	if ( has( 'star', 'sparkle', 'zap', 'flame', 'gift', 'party', 'award', 'trophy', 'crown', 'badge' ) ) return 'pop';
	if ( has( 'bounce', 'download', 'upload', 'inbox', 'mail', 'message', 'package', 'box', 'cart', 'bag' ) ) return 'bounce';
	return 'tilt';
}

const icons = {};
for ( const name of Object.keys( nodes ).sort() ) icons[ name ] = markup( nodes[ name ] );

const phpString = ( s ) => `'${ s.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }'`;
const phpArray = ( map ) =>
	`array(\n${ Object.entries( map )
		.map( ( [ k, v ] ) => `\t${ phpString( k ) } => ${ phpString( v ) },` )
		.join( '\n' ) }\n)`;

const header = ( what ) =>
	`<?php\n/**\n * ${ what }\n * Generated by scripts/build-icons.mjs from lucide-static ${ lucideVersion }. Do not edit.\n * Lucide: https://lucide.dev/icons/ (ISC License, see LICENSE-lucide.txt).\n */\n\ndefined( 'ABSPATH' ) || exit;\n\nreturn `;

mkdirSync( resolve( root, 'includes' ), { recursive: true } );
writeFileSync( resolve( root, 'includes/lucide-icons.php' ), `${ header( 'Lucide icons: name => inner SVG markup (24 x 24, stroke only).' ) }${ phpArray( icons ) };\n` );

const animatedMap = {};
for ( const name of animated ) if ( icons[ name ] ) animatedMap[ name ] = presetFor( name );
writeFileSync(
	resolve( root, 'includes/lucide-animated.php' ),
	`${ header( 'Lucide Animated (https://lucide-animated.com): the icons it animates that Lucide also has, each with the closest CSS preset.' ) }${ phpArray( animatedMap ) };\n`
);

const tagMap = {};
for ( const name of Object.keys( icons ) ) tagMap[ name ] = tags[ name ] || [];
writeFileSync( resolve( root, 'includes/lucide-tags.json' ), JSON.stringify( tagMap ) );

writeFileSync( resolve( root, 'LICENSE-lucide.txt' ), readFileSync( require.resolve( 'lucide-static/LICENSE' ), 'utf8' ) );

console.log( `icons: ${ Object.keys( icons ).length } Lucide, ${ Object.keys( animatedMap ).length } Lucide Animated (lucide-static ${ lucideVersion })` );
